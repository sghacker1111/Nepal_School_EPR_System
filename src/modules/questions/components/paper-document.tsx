type PaperDocumentProps = {
  paper: {
    title: string;
    setCode: string;
    fullMarks: { toString(): string };
    passMarks: { toString(): string } | null;
    durationMinutes: number;
    instructions: string | null;
    school: { name: string; address: string; district: string };
    academicYear: { name: string };
    class: { name: string };
    subject: { name: string };
    items: Array<{
      id: string;
      displayOrder: number;
      marks: { toString(): string };
      question: {
        questionText: string;
        questionType: string;
        answer: string | null;
        solution: string | null;
        options: Array<{
          id: string;
          label: string;
          text: string;
          isCorrect: boolean;
        }>;
      };
    }>;
  };
  showAnswers?: boolean;
};

export function PaperDocument({
  paper,
  showAnswers = false,
}: PaperDocumentProps) {
  const allocated = paper.items.reduce(
    (sum, item) => sum + Number(item.marks.toString()),
    0,
  );
  const incomplete =
    Math.round(allocated * 100) !==
    Math.round(Number(paper.fullMarks.toString()) * 100);
  return (
    <article className="mx-auto max-w-4xl bg-white p-6 text-slate-950 sm:p-10 print:max-w-none print:p-0">
      {incomplete && (
        <p
          role="alert"
          className="mb-4 border-2 border-amber-700 p-3 font-bold text-amber-900"
        >
          INCOMPLETE DRAFT — {allocated} of {paper.fullMarks.toString()} marks
          allocated. Regenerate the set before using this paper.
        </p>
      )}
      <header className="border-b-2 border-slate-900 pb-4 text-center">
        <h1 className="text-2xl font-black uppercase">{paper.school.name}</h1>
        <p className="text-sm">
          {paper.school.address} · {paper.school.district}, Nepal
        </p>
        <h2 className="mt-4 text-xl font-bold">
          {showAnswers ? "Answer Key & Marking Scheme" : paper.title}
        </h2>
        <p>
          {paper.academicYear.name} · {paper.class.name} · {paper.subject.name}{" "}
          · Set {paper.setCode}
        </p>
      </header>
      <div className="grid grid-cols-2 gap-3 border-b py-4 text-sm sm:grid-cols-4">
        <p>
          <strong>Full marks:</strong> {paper.fullMarks.toString()}
        </p>
        <p>
          <strong>Pass marks:</strong> {paper.passMarks?.toString() ?? "—"}
        </p>
        <p>
          <strong>Time:</strong> {paper.durationMinutes} minutes
        </p>
        <p>
          <strong>Set:</strong> {paper.setCode}
        </p>
      </div>
      {!showAnswers && paper.instructions && (
        <p className="my-4 rounded-lg bg-slate-50 p-3 text-sm">
          <strong>Instructions:</strong> {paper.instructions}
        </p>
      )}
      <ol className="mt-6 space-y-6">
        {paper.items.map((item) => (
          <li key={item.id} className="break-inside-avoid">
            <div className="flex gap-3">
              <span className="font-bold">{item.displayOrder}.</span>
              <div className="flex-1">
                <p className="whitespace-pre-wrap font-medium">
                  {item.question.questionText}{" "}
                  <span className="float-right ml-3 text-sm">
                    [{item.marks.toString()}]
                  </span>
                </p>
                {item.question.options.length > 0 && (
                  <ol className="mt-2 grid gap-1 pl-3 text-sm sm:grid-cols-2">
                    {item.question.options.map((option) => (
                      <li key={option.id}>
                        {option.label}. {option.text}
                        {showAnswers && option.isCorrect ? " ✓" : ""}
                      </li>
                    ))}
                  </ol>
                )}
                {showAnswers && (
                  <div className="mt-3 border-l-2 border-emerald-500 pl-3 text-sm">
                    <p>
                      <strong>Answer:</strong>{" "}
                      {item.question.answer ||
                        item.question.options.find((option) => option.isCorrect)
                          ?.label ||
                        "Not provided"}
                    </p>
                    {item.question.solution && (
                      <p className="mt-1">
                        <strong>Solution:</strong> {item.question.solution}
                      </p>
                    )}
                  </div>
                )}
              </div>
            </div>
          </li>
        ))}
      </ol>
      <footer className="mt-12 border-t pt-3 text-center text-xs text-slate-500">
        {showAnswers
          ? "Confidential teacher copy"
          : `Question paper · Set ${paper.setCode}`}{" "}
        · Page generated by Nepal School ERP
      </footer>
    </article>
  );
}
